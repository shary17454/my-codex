function paragraph(text, style = "Normal", opts = {}) {
  addWords(text);
  const styleXml = style ? `<w:pStyle w:val="${style}"/>` : "";
  const jc = `<w:jc w:val="${opts.align || "right"}"/>`;
  const bidi = opts.bidi === false ? "" : "<w:bidi/>";
  const keepNext = opts.keepNext ? "<w:keepNext/>" : "";
  const pageBreakBefore = opts.pageBreakBefore ? "<w:pageBreakBefore/>" : "";
  const spacing = opts.spacing
    ? `<w:spacing w:before="${opts.spacing.before ?? 0}" w:after="${opts.spacing.after ?? 120}" w:line="${opts.spacing.line ?? 320}" w:lineRule="auto"/>`
    : "";
  const runProps = runPropsXml(opts.run || {});
  const preserve = /^\s|\s$/.test(text) ? ` xml:space="preserve"` : "";
  return `<w:p><w:pPr>${styleXml}${keepNext}${pageBreakBefore}${bidi}${jc}${spacing}</w:pPr><w:r>${runProps}<w:t${preserve}>${esc(text)}</w:t></w:r></w:p>`;
}

function runPropsXml(opts = {}) {
  const size = opts.size ? `<w:sz w:val="${Math.round(opts.size * 2)}"/><w:szCs w:val="${Math.round(opts.size * 2)}"/>` : "";
  const bold = opts.bold ? "<w:b/><w:bCs/>" : "";
  const italic = opts.italic ? "<w:i/><w:iCs/>" : "";
  const color = opts.color ? `<w:color w:val="${opts.color}"/>` : "";
  const font = opts.font || "Arial";
  return `<w:rPr><w:rFonts w:ascii="${font}" w:hAnsi="${font}" w:cs="${font}"/>${bold}${italic}${color}${size}<w:rtl/><w:lang w:val="ar-SA" w:bidi="ar-SA"/></w:rPr>`;
}

function fieldRun(instr, resultText = "") {
  return [
    `<w:r>${runPropsXml()}<w:fldChar w:fldCharType="begin"/></w:r>`,
    `<w:r>${runPropsXml()}<w:instrText xml:space="preserve">${esc(instr)}</w:instrText></w:r>`,
    `<w:r>${runPropsXml()}<w:fldChar w:fldCharType="separate"/></w:r>`,
    `<w:r>${runPropsXml()}<w:t>${esc(resultText)}</w:t></w:r>`,
    `<w:r>${runPropsXml()}<w:fldChar w:fldCharType="end"/></w:r>`,
  ].join("");
}

function fieldParagraph(instr, resultText, style = "Normal") {
  return `<w:p><w:pPr><w:pStyle w:val="${style}"/><w:bidi/><w:jc w:val="right"/></w:pPr>${fieldRun(instr, resultText)}</w:p>`;
}

