function caption(type, title) {
  const seq = type === "table" ? "Table" : "Figure";
  const label = type === "table" ? "جدول" : "شكل";
  const arr = type === "table" ? tableIndex : figureIndex;
  arr.push(`${label} ${arr.length + 1}: ${title}`);
  addWords(`${label} ${arr.length}: ${title}`);
  htmlParts.push(`<p class="caption">${htmlEsc(`${label} ${arr.length}: ${title}`)}</p>`);
  elements.push(
    `<w:p><w:pPr><w:pStyle w:val="Caption"/><w:bidi/><w:jc w:val="center"/><w:spacing w:before="80" w:after="120"/></w:pPr>` +
      `<w:r>${runPropsXml({ bold: true, color: "1F4D78" })}<w:t>${esc(label)} </w:t></w:r>` +
      fieldRun(`SEQ ${seq} \\* ARABIC`, String(arr.length)) +
      `<w:r>${runPropsXml({ bold: true, color: "1F4D78" })}<w:t>${esc(": " + title)}</w:t></w:r></w:p>`
  );
}

function table(headers, rows, widths, title) {
  if (title) caption("table", title);
  const total = widths.reduce((a, b) => a + b, 0);
  const norm = widths.map((w) => Math.round((w / total) * 9360));
  norm[norm.length - 1] += 9360 - norm.reduce((a, b) => a + b, 0);
  const grid = norm.map((w) => `<w:gridCol w:w="${w}"/>`).join("");
  const headerRow = rowXml(headers, norm, true);
  const bodyRows = rows.map((r) => rowXml(r, norm, false)).join("");
  elements.push(
    `<w:tbl><w:tblPr><w:bidiVisual/><w:tblW w:w="9360" w:type="dxa"/><w:tblInd w:w="120" w:type="dxa"/><w:tblLayout w:type="fixed"/><w:tblCellMar><w:top w:w="90" w:type="dxa"/><w:left w:w="120" w:type="dxa"/><w:bottom w:w="90" w:type="dxa"/><w:right w:w="120" w:type="dxa"/></w:tblCellMar><w:tblBorders><w:top w:val="single" w:sz="4" w:space="0" w:color="B8C2CC"/><w:left w:val="single" w:sz="4" w:space="0" w:color="B8C2CC"/><w:bottom w:val="single" w:sz="4" w:space="0" w:color="B8C2CC"/><w:right w:val="single" w:sz="4" w:space="0" w:color="B8C2CC"/><w:insideH w:val="single" w:sz="4" w:space="0" w:color="D6DDE5"/><w:insideV w:val="single" w:sz="4" w:space="0" w:color="D6DDE5"/></w:tblBorders></w:tblPr><w:tblGrid>${grid}</w:tblGrid>${headerRow}${bodyRows}</w:tbl>`
  );
  htmlParts.push(
    `<table><thead><tr>${headers.map((h) => `<th>${htmlEsc(h)}</th>`).join("")}</tr></thead><tbody>${rows
      .map((row) => `<tr>${row.map((cell) => `<td>${String(cell).split(/\n+/).map(htmlEsc).join("<br>")}</td>`).join("")}</tr>`)
      .join("")}</tbody></table>`
  );
  elements.push(paragraph("", "Normal", { spacing: { before: 0, after: 80, line: 280 } }));
}

function rowXml(cells, widths, header) {
  const rowProps = header ? "<w:trPr><w:tblHeader/></w:trPr>" : "";
  const fill = header ? `<w:shd w:fill="E8EEF5"/>` : "";
  const cellXml = cells
    .map((cell, i) => {
      const txt = textOnly(cell);
      addWords(txt);
      const paras = String(cell)
        .split(/\n+/)
        .map((line) => `<w:p><w:pPr><w:bidi/><w:jc w:val="right"/><w:spacing w:after="40" w:line="280" w:lineRule="auto"/></w:pPr><w:r>${runPropsXml({ bold: header, size: header ? 10.5 : 10 })}<w:t>${esc(line)}</w:t></w:r></w:p>`)
        .join("");
      return `<w:tc><w:tcPr><w:tcW w:w="${widths[i]}" w:type="dxa"/>${fill}<w:vAlign w:val="center"/><w:tcMar><w:top w:w="90" w:type="dxa"/><w:left w:w="120" w:type="dxa"/><w:bottom w:w="90" w:type="dxa"/><w:right w:w="120" w:type="dxa"/></w:tcMar></w:tcPr>${paras}</w:tc>`;
    })
    .join("");
  return `<w:tr>${rowProps}${cellXml}</w:tr>`;
}

